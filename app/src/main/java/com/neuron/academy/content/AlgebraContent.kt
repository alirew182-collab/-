            theory = """
                ### Показательная функция
                \(y = a^x\), где \(a > 0, a \ne 1\). При \(a > 1\) возрастает, при \(0 < a < 1\) убывает. Всегда \(a^x > 0\).

                ### Простейшие уравнения
                \[a^{f(x)} = a^{g(x)} \Rightarrow f(x) = g(x)\]
                Пример: \(2^x = 32 = 2^5 \Rightarrow x = 5\).

                ### Если основания не сводятся
                Логарифмируем: \(3^x = 7 \Rightarrow x = \log_3 7\).

                ### Замена переменной
                \(4^x - 3\cdot 2^x - 4 = 0\). Пусть \(t = 2^x > 0\): \(t^2 - 3t - 4 = 0 \Rightarrow t = 4\) (корень −1 не подходит), \(x = 2\).

                ### Неравенства
                При \(a > 1\): \(a^x > a^y \iff x > y\). При \(0 < a < 1\) знак меняется!
