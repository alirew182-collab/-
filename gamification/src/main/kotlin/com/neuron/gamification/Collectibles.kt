enum class CardType(val title: String) { SCIENTIST("Учёные"), ELEMENT("Элементы") }
enum class Rarity(val title: String, val color: Long) {
    COMMON("Обычная", 0xFF78909C),
    RARE("Редкая", 0xFF42A5F5),
    EPIC("Эпическая", 0xFFAB47BC),
    LEGENDARY("Легендарная", 0xFFFFB300),
}

data class CardDef(
    val id: String,
    val title: String,
    val subtitle: String,
    val emoji: String,
    val fact: String,
    val type: CardType,
    val rarity: Rarity,
)

